const execFileAsync = promisify(execFile);

export const decisionStatuses = ["proposed", "accepted", "superseded"] as const;
export type DecisionStatus = (typeof decisionStatuses)[number];

const defaultDecisionsDir = path.join("wiki", "decisions");
// A repo that already keeps ADRs elsewhere keeps them there instead of gaining a second home.
const existingDecisionDirs = [defaultDecisionsDir, path.join("docs", "decisions"), path.join("docs", "adr"), "adr"];
const indexFileName = "index.md";
const indexMarker = "<!-- Generated by weave adr. Do not edit by hand. -->";
const nonDecisionFiles = new Set([indexFileName, "readme.md", "template.md"]);
const baseCandidates = ["origin/HEAD", "origin/main", "origin/master", "main", "master"];

export interface DecisionSummary {
  id: string;
  title: string;
  // `unknown` is an ADR written outside Weave whose status could not be read.
  status: DecisionStatus | "unknown";
  date?: string;
  owner?: string;
  change?: string;
  applies_to: string[];
  supersedes: string[];
  superseded_by?: string;
  path: string;
  managed: boolean;
}

export interface NewDecisionOptions {
  cwd: string;
  title: string;
  slug?: string;
  appliesTo?: readonly string[];
  supersedes?: readonly string[];
  owner?: string;
  now?: Date;
  randomId?: () => string;
  sessionPath?: string;
}

export interface NewDecisionResult {
  status: "ok";
  decision: DecisionSummary;
  message: string;
}

export interface ListDecisionsOptions {
  cwd: string;
  status?: DecisionStatus;
  filePath?: string;
  sessionPath?: string;
}

export interface ListDecisionsResult {
  status: "ok";
  directory: string;
  decisions: DecisionSummary[];
  message: string;
}

export interface SetDecisionStatusOptions {
  cwd: string;
  decision: string;
  status: DecisionStatus;
  supersededBy?: string;
  sessionPath?: string;
}

export interface SetDecisionStatusResult {
  status: "ok";
  decision: DecisionSummary;
  superseded: DecisionSummary[];
  message: string;
}

export interface CheckDecisionsOptions {
  cwd: string;
  base?: string;
  sessionPath?: string;
}

export interface TouchedDecision {
  decision: DecisionSummary;
  files: string[];
}

export interface CheckDecisionsResult {
  status: "ok";
  repos: { path: string; base: string | null }[];
  skipped: { path: string; reason: string }[];
  changed_files: string[];
  touched: TouchedDecision[];
  // Live decisions with no Applies To paths can never be matched, so they are reported separately.
  without_paths: DecisionSummary[];
  message: string;
}

export type DecisionGuidanceResult = "created" | "appended" | "unchanged";

export const decisionGuidanceMarker = "<!-- weave:decisions -->";

export function isDecisionStatus(value: unknown): value is DecisionStatus {
  return typeof value === "string" && (decisionStatuses as readonly string[]).includes(value);
}

export async function newDecision(options: NewDecisionOptions): Promise<NewDecisionResult> {
  const title = options.title.trim();
  if (!title) {
    throw new ChangeCommandError("missing_title", "Decision title is required");
  }

  const now = options.now ?? new Date();
  const root = await resolveRoot(options.cwd, options.sessionPath);
  const directory = await resolveDecisionsDir(root);
  const existing = await readDecisions(root, directory);
  const supersedes = (options.supersedes ?? []).map((reference) => resolveDecision(existing, reference).id);
  const slug = slugify(options.slug ?? title, "decision");
  const appliesTo = (options.appliesTo ?? []).map((entry) => toRootRelative(entry)).filter(Boolean);

  await mkdir(path.join(root, directory), { recursive: true });
  const id = await generateDecisionId(root, directory, slug, now, options.randomId ?? randomChangeIdPart);
  const owner = options.owner?.trim() || (await gitConfigUserName(root));
  const change = await activeChangeId(options.cwd, options.sessionPath);

  const relativePath = path.join(directory, `${id}.md`);
  await writeFile(
    path.join(root, relativePath),
    `${decisionFrontmatter({
      id,
      title,
      status: "proposed",
      date: formatIsoDate(now),
      owner,
      change,
      applies_to: appliesTo,
      supersedes,
    })}${decisionBodyTemplate(title)}`,
    { flag: "wx" },
  );
  await writeDecisionIndex(root, directory);

  const decision = resolveDecision(await readDecisions(root, directory), id);
  return { status: "ok", decision, message: `Created proposed decision ${id} at ${relativePath}.` };
}

export async function listDecisions(options: ListDecisionsOptions): Promise<ListDecisionsResult> {
  const root = await resolveRoot(options.cwd, options.sessionPath);
  const directory = await resolveDecisionsDir(root);
  let decisions = await readDecisions(root, directory);

  if (options.status) {
    decisions = decisions.filter((decision) => decision.status === options.status);
  }
  if (options.filePath) {
    const target = toRootRelative(path.relative(root, path.resolve(await realpath(options.cwd), options.filePath)));
    decisions = decisions.filter((decision) => decision.applies_to.some((pattern) => matchesAppliesTo(target, pattern)));
  }

  return {
    status: "ok",
    directory: toPosix(directory),
    decisions,
    message: formatDecisionList(decisions),
  };
}

export async function setDecisionStatus(options: SetDecisionStatusOptions): Promise<SetDecisionStatusResult> {
  const root = await resolveRoot(options.cwd, options.sessionPath);
  const directory = await resolveDecisionsDir(root);
  const decisions = await readDecisions(root, directory);
  const decision = requireManaged(resolveDecision(decisions, options.decision));
  const superseded: DecisionSummary[] = [];

  if (decision.status === "superseded") {
    throw invalidTransition(decision, options.status);
  }

  if (options.status === "superseded") {
    if (!options.supersededBy) {
      throw new ChangeCommandError("missing_superseded_by", "Marking a decision superseded needs --superseded-by <decision>.");
    }
    const replacement = resolveDecision(decisions, options.supersededBy);
    if (replacement.id === decision.id) {
      throw new ChangeCommandError("invalid_superseded_by", "A decision cannot supersede itself.");
    }
    await updateFrontmatter(root, decision, { status: "superseded", superseded_by: replacement.id });
    superseded.push(decision);
  } else if (options.status === "accepted") {
    if (decision.status === "accepted") {
      throw invalidTransition(decision, options.status);
    }
    await updateFrontmatter(root, decision, { status: "accepted" });
    // Accepting a replacement is what retires the decisions it names.
    for (const reference of decision.supersedes) {
      const target = decisions.find((candidate) => candidate.id === reference);
      if (target?.managed && target.status !== "superseded") {
        await updateFrontmatter(root, target, { status: "superseded", superseded_by: decision.id });
        superseded.push(target);
      }
    }
  } else {
    throw invalidTransition(decision, options.status);
  }

  await writeDecisionIndex(root, directory);
  const updated = await readDecisions(root, directory);
  const supersededIds = superseded.map((entry) => entry.id);
  return {
    status: "ok",
    decision: resolveDecision(updated, decision.id),
    superseded: updated.filter((entry) => supersededIds.includes(entry.id) && entry.id !== decision.id),
    message: `Decision ${decision.id} is now ${options.status}.${
      options.status === "accepted" && supersededIds.length > 0 ? ` Superseded: ${supersededIds.join(", ")}.` : ""
    }`,
  };
}

export async function checkDecisions(options: CheckDecisionsOptions): Promise<CheckDecisionsResult> {
  const root = await resolveRoot(options.cwd, options.sessionPath);
  const directory = await resolveDecisionsDir(root);
  const live = (await readDecisions(root, directory)).filter(
    (decision) => decision.status !== "superseded",
  );

  const repos: CheckDecisionsResult["repos"] = [];
  const skipped: CheckDecisionsResult["skipped"] = [];
  const changed = new Set<string>();
  for (const repoPath of await repoPaths(root)) {
    const absolute = path.join(root, repoPath);
    if (!(await isGitRepoRoot(absolute))) {
      skipped.push({ path: repoPath || ".", reason: "not a git repository" });
      continue;
    }
    const base = await resolveBase(absolute, options.base);
    repos.push({ path: repoPath || ".", base });
    for (const file of await changedFiles(absolute, base)) {
      changed.add(toPosix(path.join(repoPath, file)));
    }
  }

  const decisionsPrefix = `${toPosix(directory)}/`;
  const changedFilesList = [...changed].filter((file) => !file.startsWith(decisionsPrefix)).sort();
  const touched = live.flatMap((decision) => {
    const files = changedFilesList.filter((file) => decision.applies_to.some((pattern) => matchesAppliesTo(file, pattern)));
    return files.length > 0 ? [{ decision, files }] : [];
  });
  const withoutPaths = live.filter((decision) => decision.applies_to.length === 0);

  return {
    status: "ok",
    repos,
    skipped,
    changed_files: changedFilesList,
    touched,
    without_paths: withoutPaths,
    message: formatCheckMessage(changedFilesList, touched, withoutPaths),
  };
}

// Paths are relative to the Weave root. A pattern without wildcards matches that file or
// anything under that folder; `*` stays within one path segment and `**` crosses them.
export function matchesAppliesTo(file: string, pattern: string): boolean {
  const normalizedFile = toRootRelative(file);
  const normalizedPattern = toRootRelative(pattern).replace(/\/+$/, "");
  if (!normalizedPattern) {
    return false;
  }
  if (!/[*?]/.test(normalizedPattern)) {
    return normalizedFile === normalizedPattern || normalizedFile.startsWith(`${normalizedPattern}/`);
  }
  return globToRegExp(normalizedPattern).test(normalizedFile);
}

// Appends only: an existing AGENTS.md keeps everything it already says.
export async function ensureDecisionGuidance(root: string): Promise<DecisionGuidanceResult> {
  const agentsPath = path.join(root, "AGENTS.md");
  if (!(await pathExists(agentsPath))) {
    await writeFile(agentsPath, `# Agent instructions\n\n${decisionGuidanceBlock()}`);
    return "created";
  }

  const current = await readFile(agentsPath, "utf8");
  if (current.includes(decisionGuidanceMarker)) {
    return "unchanged";
  }

  const separator = current.endsWith("\n\n") ? "" : current.endsWith("\n") ? "\n" : "\n\n";
  await writeFile(agentsPath, `${current}${separator}${decisionGuidanceBlock()}`);
  return "appended";
}

function decisionGuidanceBlock(): string {
  return `${decisionGuidanceMarker}
## Recorded engineering decisions

This project records long-lived engineering decisions as ADRs. Before planning or changing code:

1. Run \`weave adr list --path <file> --json\` for the files you expect to touch, and read the accepted decisions it returns.
2. Work inside those decisions. If a task would conflict with one, stop and say so; propose a superseding decision with \`weave adr new "<title>" --supersedes <id>\` rather than changing it quietly.
3. If a decision's \`Reconsider When\` condition seems to apply, raise it. It may be out of date, but that is a choice for the team, not the agent.
4. When you finish, name the decisions you consulted. \`weave adr check\` lists any decisions the current branch touches.
`;
}

function globToRegExp(pattern: string): RegExp {
  let source = "";
  for (let index = 0; index < pattern.length; index += 1) {
    const char = pattern[index];
    if (char === "*" && pattern[index + 1] === "*") {
      if (pattern[index + 2] === "/") {
        source += "(?:.*/)?";
        index += 2;
      } else {
        source += ".*";
        index += 1;
      }
    } else if (char === "*") {
      source += "[^/]*";
    } else if (char === "?") {
      source += "[^/]";
    } else {
      source += char.replace(/[.+^${}()|[\]\\]/g, "\\$&");
    }
  }
  return new RegExp(`^${source}$`);
}

async function resolveRoot(cwd: string, sessionPath?: string): Promise<string> {
  const context = await resolveChangeContext(cwd, sessionPath ?? defaultSessionPath());
  if (!context) {
    throw new ChangeCommandError("no_weave_context", "No Weave context found. Run `weave init` first.");
  }
  return context.rootPath;
}

async function resolveDecisionsDir(root: string): Promise<string> {
  for (const candidate of existingDecisionDirs) {
    if (await pathExists(path.join(root, candidate))) {
      return candidate;
    }
  }
  return defaultDecisionsDir;
}

async function readDecisions(root: string, directory: string): Promise<DecisionSummary[]> {
  const absolute = path.join(root, directory);
  if (!(await pathExists(absolute))) {
    return [];
  }

  const entries = await readdir(absolute, { withFileTypes: true });
  const decisions = await Promise.all(
    entries
      .filter((entry) => entry.isFile() && path.extname(entry.name) === ".md" && !nonDecisionFiles.has(entry.name.toLowerCase()))
      .map(async (entry) => parseDecision(entry.name, directory, await readFile(path.join(absolute, entry.name), "utf8"))),
  );
  return decisions.sort((left, right) => right.id.localeCompare(left.id));
}

function parseDecision(fileName: string, directory: string, content: string): DecisionSummary {
  const relativePath = toPosix(path.join(directory, fileName));
  const fallbackId = path.basename(fileName, ".md");
  const frontmatter = parseFrontmatter(content);

  if (frontmatter && isDecisionStatus(frontmatter.status) && typeof frontmatter.id === "string") {
    return {
      id: frontmatter.id,
      title: typeof frontmatter.title === "string" ? frontmatter.title : fallbackId,
      status: frontmatter.status,
      ...(frontmatter.date ? { date: String(frontmatter.date) } : {}),
      ...(typeof frontmatter.owner === "string" ? { owner: frontmatter.owner } : {}),
      ...(typeof frontmatter.change === "string" ? { change: frontmatter.change } : {}),
      applies_to: stringList(frontmatter.applies_to),
      supersedes: stringList(frontmatter.supersedes),
      ...(typeof frontmatter.superseded_by === "string" ? { superseded_by: frontmatter.superseded_by } : {}),
      path: relativePath,
      managed: true,
    };
  }

  // An ADR written before Weave managed this folder: readable, but left as its author wrote it.
  return {
    id: fallbackId,
    title: /^#\s+(.+)$/m.exec(content)?.[1]?.trim() ?? fallbackId,
    status: foreignStatus(content),
    applies_to: [],
    supersedes: [],
    path: relativePath,
    managed: false,
  };
}

function foreignStatus(content: string): DecisionSummary["status"] {
  const match = /^(?:#+\s*)?status:?\s*\n*\s*([a-z-]+)/im.exec(content);
  const value = match?.[1]?.toLowerCase();
  return isDecisionStatus(value) ? value : "unknown";
}

function parseFrontmatter(content: string): Record<string, unknown> | undefined {
  const match = /^---\n([\s\S]*?)\n---/.exec(content);
  if (!match) {
    return undefined;
  }
  try {
    const parsed = YAML.parse(match[1]) as unknown;
    return parsed && typeof parsed === "object" ? (parsed as Record<string, unknown>) : undefined;
  } catch {
    return undefined;
  }
}

async function updateFrontmatter(root: string, decision: DecisionSummary, changes: Record<string, unknown>): Promise<void> {
  const filePath = path.join(root, decision.path);
  const content = await readFile(filePath, "utf8");
  const match = /^---\n([\s\S]*?)\n---\n/.exec(content);
  if (!match) {
    throw new ChangeCommandError("invalid_decision", `Decision ${decision.id} has no frontmatter.`);
  }
  const frontmatter = { ...(YAML.parse(match[1]) as Record<string, unknown>), ...changes };
  await writeFile(filePath, `---\n${YAML.stringify(frontmatter, { lineWidth: 0 })}---\n${content.slice(match[0].length)}`);
}

function resolveDecision(decisions: DecisionSummary[], reference: string): DecisionSummary {
  const value = path.basename(reference.trim(), ".md");
  const exact = decisions.find((decision) => decision.id === value);
  if (exact) {
    return exact;
  }

  const matches = decisions.filter((decision) => decision.id.includes(value));
  if (matches.length === 1) {
    return matches[0];
  }
  if (matches.length > 1) {
    throw new ChangeCommandError("ambiguous_decision", `Decision reference "${reference}" matches ${matches.map((match) => match.id).join(", ")}.`, {
      matches: matches.map((match) => match.id),
    });
  }
  throw new ChangeCommandError("unknown_decision", `No decision matches "${reference}".`);
}

function requireManaged(decision: DecisionSummary): DecisionSummary {
  if (!decision.managed) {
    throw new ChangeCommandError(
      "unmanaged_decision",
      `Decision ${decision.id} was not written by Weave, so its status has to be edited by hand.`,
    );
  }
  return decision;
}

function invalidTransition(decision: DecisionSummary, status: DecisionStatus): ChangeCommandError {
  return new ChangeCommandError(
    "invalid_status_transition",
    `Decision ${decision.id} cannot move from ${decision.status} to ${status}. Accepted decisions change only by being superseded.`,
    { from: decision.status, to: status },
  );
}

async function generateDecisionId(
  root: string,
  directory: string,
  slug: string,
  now: Date,
  randomId: () => string,
): Promise<string> {
  for (let attempt = 0; attempt < 10; attempt += 1) {
    const id = `${formatDatePrefix(now)}-${randomId()}-${slug}`;
    if (!(await pathExists(path.join(root, directory, `${id}.md`)))) {
      return id;
    }
  }
  throw new ChangeCommandError("decision_id_collision", "Could not generate a unique decision id.");
}

async function activeChangeId(cwd: string, sessionPath?: string): Promise<string | undefined> {
  try {
    return (await activeChangeContext({ cwd, sessionPath })).change.id;
  } catch {
    return undefined;
  }
}

async function writeDecisionIndex(root: string, directory: string): Promise<void> {
  const indexPath = path.join(root, directory, indexFileName);
  if ((await pathExists(indexPath)) && !(await readFile(indexPath, "utf8")).includes(indexMarker)) {
    // The folder already has an index someone wrote by hand. `weave adr list` still works without it.
    return;
  }

  const decisions = await readDecisions(root, directory);
  const rows = decisions.map(
    (decision) =>
      `| [${decision.id}](${path.basename(decision.path)}) | ${escapeCell(decision.title)} | ${decision.status} | ${
        decision.applies_to.map((entry) => `\`${entry}\``).join(", ") || "-"
      } |`,
  );
  await writeFile(
    indexPath,
    [
      "# Decisions",
      "",
      indexMarker,
      "",
      "| Decision | Title | Status | Applies to |",
      "| --- | --- | --- | --- |",
      ...rows,
      "",
    ].join("\n"),
  );
}

function decisionFrontmatter(input: {
  id: string;
  title: string;
  status: DecisionStatus;
  date: string;
  owner?: string;
  change?: string;
  applies_to: string[];
  supersedes: string[];
}): string {
  const fields = {
    id: input.id,
    title: input.title,
    status: input.status,
    date: input.date,
    ...(input.owner ? { owner: input.owner } : {}),
    ...(input.change ? { change: input.change } : {}),
    applies_to: input.applies_to,
    supersedes: input.supersedes,
    superseded_by: null,
  };
  return `---\n${YAML.stringify(fields, { lineWidth: 0 })}---\n\n`;
}

function decisionBodyTemplate(title: string): string {
  return `# ${title}

## Context

<!-- What forced this decision, and the constraints at the time. -->

## Decision

<!-- What was decided, in a sentence or two. -->

## Alternatives Rejected

<!-- Each serious alternative, and why it lost. -->

## Consequences

<!-- What this makes easier and harder, and what is now accepted as a cost. -->

## Reconsider When

<!-- The conditions that would make this worth revisiting. -->
`;
}

async function repoPaths(root: string): Promise<string[]> {
  const metadata = await readWorkspaceMetadata(root);
  const repos = metadata?.mode === "workspace" ? Object.values(metadata.repos).map((repo) => repo.path) : [];
  return ["", ...repos];
}

async function isGitRepoRoot(absolute: string): Promise<boolean> {
  if (!(await pathExists(absolute))) {
    return false;
  }
  const topLevel = await gitOutput(["rev-parse", "--show-toplevel"], absolute);
  return Boolean(topLevel) && (await realpath(topLevel as string)) === (await realpath(absolute));
}

async function resolveBase(repo: string, explicit?: string): Promise<string | null> {
  for (const candidate of explicit ? [explicit] : baseCandidates) {
    const mergeBase = await gitOutput(["merge-base", "HEAD", candidate], repo);
    if (mergeBase) {
      return mergeBase;
    }
  }
  if (explicit) {
    throw new ChangeCommandError("unknown_base", `Could not find a common ancestor with "${explicit}" in ${repo}.`);
  }
  return null;
}

async function changedFiles(repo: string, base: string | null): Promise<string[]> {
  const committed = base ? await gitOutput(["diff", "--name-only", base, "HEAD"], repo) : undefined;
  const uncommitted = await gitOutput(["diff", "--name-only", "HEAD"], repo);
  const untracked = await gitOutput(["ls-files", "--others", "--exclude-standard"], repo);
  return [committed, uncommitted, untracked].flatMap((output) => (output ? output.split("\n").filter(Boolean) : []));
}

async function gitOutput(args: string[], cwd: string): Promise<string | undefined> {
  try {
    const { stdout } = await execFileAsync("git", args, { cwd, maxBuffer: 32 * 1024 * 1024 });
    return stdout.trim() || undefined;
  } catch {
    return undefined;
  }
}

async function gitConfigUserName(root: string): Promise<string | undefined> {
  return gitOutput(["config", "user.name"], root);
}

function formatDecisionList(decisions: DecisionSummary[]): string {
  if (decisions.length === 0) {
    return "No decisions found.";
  }
  return decisions.map((decision) => `${decision.id} [${decision.status}] ${decision.title}`).join("\n");
}

function formatCheckMessage(changed: string[], touched: TouchedDecision[], withoutPaths: DecisionSummary[]): string {
  const lines: string[] = [];
  if (touched.length === 0) {
    lines.push(`No recorded decisions apply to the ${changed.length} changed file(s).`);
  } else {
    lines.push(`${touched.length} decision(s) apply to the ${changed.length} changed file(s):`);
    for (const { decision, files } of touched) {
      lines.push(`- ${decision.id} [${decision.status}] ${decision.title}`);
      lines.push(...files.map((file) => `    ${file}`));
    }
  }
  if (withoutPaths.length > 0) {
    lines.push(`${withoutPaths.length} decision(s) have no Applies To paths, so they were not checked: ${withoutPaths.map((decision) => decision.id).join(", ")}`);
  }
  return lines.join("\n");
}

function formatIsoDate(now: Date): string {
  const month = String(now.getMonth() + 1).padStart(2, "0");
  const day = String(now.getDate()).padStart(2, "0");
  return `${now.getFullYear()}-${month}-${day}`;
}

function stringList(value: unknown): string[] {
  return Array.isArray(value) ? value.filter((entry): entry is string => typeof entry === "string") : [];
}

function escapeCell(value: string): string {
  return value.replace(/\|/g, "\\|");
}

function toPosix(value: string): string {
  return value.split(path.sep).join("/");
}

function toRootRelative(value: string): string {
  return toPosix(value.trim()).replace(/^\.\//, "");
}
